#!/bin/bash
# Build the shower and analysis step: the Rivet plugin library (our GGZH_NLOPS and the LHC
# Higgs WG SimplifiedTemplateCrossSections at the pinned commit) and the Pythia 8 driver
# ggzh-shower, against an LCG view.
#
#   ./build.sh <prefix>            (SHOWER_LCG_VIEW to change the view; network for the STXS clone,
#                                   or STXS_DIR=<checkout> with the pinned commit)
#
# Output: <prefix>/bin/ggzh-shower, <prefix>/lib/RivetGGZH.so, <prefix>/env.sh (relocatable),
# <prefix>/BUILD-MANIFEST.txt.  A few minutes on one core.
set -Eeo pipefail
trap 'echo "FATAL: shower/build.sh line $LINENO: $BASH_COMMAND" >&2' ERR
HERE=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
source "$HERE/versions.sh"
[ -n "$1" ] || { echo "usage: $0 <prefix>" >&2; exit 2; }
mkdir -p "$1"; PREFIX=$(cd "$1" && pwd)
mkdir -p "$PREFIX/bin" "$PREFIX/lib" "$PREFIX/src"
[ -f "$SHOWER_LCG_VIEW/setup.sh" ] || { echo "FATAL: no LCG view $SHOWER_LCG_VIEW" >&2; exit 2; }
source "$SHOWER_LCG_VIEW/setup.sh"
for t in g++ pythia8-config rivet-config rivet-build HepMC3-config; do
  command -v $t >/dev/null || { echo "FATAL: $t not in the view" >&2; exit 2; }
done

STXS=${STXS_DIR:-$PREFIX/src/stxs}
[ -d "$STXS/.git" ] || git clone -q "$STXS_URL" "$STXS"
git -C "$STXS" checkout -q "$STXS_COMMIT"

# Rivet plugins
( cd "$PREFIX/lib" && rivet-build RivetGGZH.so "$HERE/rivet/GGZH_NLOPS.cc" "$STXS/SimplifiedTemplateCrossSections.cc" \
    -I"$STXS" > "$PREFIX/lib/rivet-build.log" 2>&1 ) \
  || { echo "FATAL: rivet-build failed" >&2; tail -30 "$PREFIX/lib/rivet-build.log" >&2; exit 3; }

# Pythia driver
g++ -O2 -std=c++17 "$HERE/src/ggzh_shower.cc" -o "$PREFIX/bin/ggzh-shower" \
    $(pythia8-config --cxxflags) $(rivet-config --cppflags) $(HepMC3-config --cflags) \
    $(pythia8-config --libs) $(rivet-config --libs) $(HepMC3-config --libs) -ldl \
    > "$PREFIX/bin/build.log" 2>&1 \
  || { echo "FATAL: ggzh-shower failed to compile" >&2; tail -30 "$PREFIX/bin/build.log" >&2; exit 4; }

cat > "$PREFIX/env.sh" <<EOF
# generated by shower/build.sh; source before running
export SHOWER_LCG_VIEW=$SHOWER_LCG_VIEW
source "\$SHOWER_LCG_VIEW/setup.sh"
export GGZH_SHOWER_PREFIX=\$(cd "\$(dirname "\${BASH_SOURCE[0]}")" && pwd)
export PATH=\$GGZH_SHOWER_PREFIX/bin:\$PATH
export RIVET_ANALYSIS_PATH=\$GGZH_SHOWER_PREFIX/lib\${RIVET_ANALYSIS_PATH:+:\$RIVET_ANALYSIS_PATH}
EOF
source "$PREFIX/env.sh"
rivet --list-analyses 2>/dev/null | grep -E '^(GGZH_NLOPS|SimplifiedTemplateCrossSections)' \
  || { echo "FATAL: the analyses are not visible to Rivet" >&2; exit 5; }
{
  echo "built $(date -u +%FT%TZ) on $(hostname)"
  echo "LCG view $SHOWER_LCG_VIEW"
  echo "g++ $(g++ --version | head -1)"
  echo "Pythia $(pythia8-config --version 2>/dev/null || basename "$(dirname "$(dirname "$(readlink -f "$(command -v pythia8-config)")")")")"
  echo "Rivet $(rivet-config --version)"
  echo "HepMC3 $(HepMC3-config --version)"
  echo "STXS $(git -C "$STXS" rev-parse HEAD)"
  echo "sha256 $(sha256sum "$PREFIX/bin/ggzh-shower")"
  echo "sha256 $(sha256sum "$PREFIX/lib/RivetGGZH.so")"
} > "$PREFIX/BUILD-MANIFEST.txt"
cat "$PREFIX/BUILD-MANIFEST.txt"
echo "SHOWER-BUILD-DONE (source $PREFIX/env.sh)"
